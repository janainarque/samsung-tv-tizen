"""Stage the isolated SDK project; never run a build, sign, package or deploy."""
import json
from pathlib import Path
import sys

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "tools"))
import webapp


def main():
    files = webapp.files(dict(webapp.GENERIC), "prepare_tizen.py")
    for name in ("LICENSE", "UPSTREAM_README.md"):
        files[name] = (ROOT / name).read_bytes()
    for name in ("config.xml", "icon.png"):
        files[name] = (ROOT / "tizen" / name).read_bytes()
    output = ROOT / "tizen-app"
    for name, content in files.items():
        target = output / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)

    # Match the existing SDK project's schema, with an explicit complete allowlist.
    settings = [
        '# Generated by ../prepare_tizen.py; paths relative to this isolated project.',
        'project_type: web_app', 'profile: tv-samsung', 'api_version: "2.3"',
        'build_type: Debug', 'output_name: FreeMyTVVariant', 'output_path: ""',
        'opt: false', 'signing_profile: ""', 'trust_anchor: []', 'files:',
    ]
    settings.extend('  - ' + json.dumps(name) for name in sorted(files))
    settings.extend([
        'excludes:', '  - "Debug/*"', '  - "Release/*"', '  - "Build/*"',
        '  - "Test/*"', '  - "\\\\.tizen-rds/.*"',
        '  - "\\\\.vscode/.*"', '  - "\\\\.buildResult/.*"',
        '  - "\\\\.sign/.*"', '  - "tizen_web_project.yaml"',
        '  - "*.wgt"', 'deps: []', '',
    ])
    (output / "tizen_web_project.yaml").write_text('\n'.join(settings), encoding='utf-8')
    print('Isolated SDK project: ' + str(output))
    print('Staged resources: ' + str(len(files)))
    print('No build, signing, WGT creation or installation executed.')


if __name__ == '__main__':
    main()
